"""
Local web UI for playing a NoExit session interactively in the browser.

Wraps simulator.py's session functions behind a small JSON API and serves
webapp.html as the frontend. Single-user, local only -- state lives in one
module-level GameState, matching session_state.json's existing single-session
assumption (same as run_session.py's CLI loop, just driven from a browser
instead of stdin).

Usage:
    python tools/webapp.py
"""

import json
import random
from urllib.parse import unquote
import webbrowser
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

import library
import runs as runstore
from game_state import config, assembly
import simulator
import store
from _paths import PROJECT_ROOT, UI
from save_version import current_version, compute_file_diffs, ROOT

HOST = "127.0.0.1"
PORT = 8765
WEBAPP_HTML = UI / "webapp.html"

state = None  # current game.GameState, or None if no session is active

# What the live session was built from: None for a generated pair, or
# {"kind": "seated", "char_ids": [...]} for one seated from the library. The client
# needs this to know that "Generate New Pair" would destroy a chosen pair. Assigned
# only through _set_session, so it cannot be left describing a previous session.
session_source = None


def _set_session(new_state, source=None):
    global state, session_source
    state, session_source = new_state, source


def drifted_files():
    """
    Files in live game_state/ that differ from the version CURRENT names.

    Any drift means this run was generated by prompts that no version captures,
    so tagging it with CURRENT would record a version that cannot reproduce it.
    Returns [] when in sync, or None if there is no version to compare against.
    """
    current = current_version()
    if current is None:
        return None
    return sorted(str(rel) for rel in compute_file_diffs(current, ROOT))


def char_payload(char):
    if char is None or not char.description:
        return None
    return {
        "name": char.name, "age": char.age, "gender": char.gender,
        "occupation": char.occupation, "description": char.description,
    }


def _active_session_error(body):
    """
    The message for a 409 when a session is already live, or None to proceed.

    /api/new and /api/chars_only used to reassign the global with no check, silently
    destroying an in-progress session. {"force": true} still allows it.
    """
    if state is None or (body or {}).get("force"):
        return None
    return (f"A session is active ({state.session_id}, {state.turn_count} turns). "
            "Save or abandon it first, or send force to discard it.")


# Models this project has actually called, for the dropdowns. Harness-side on purpose:
# config.py is the Unity mirror and holds the models in use, not a catalogue of options.
# Anything already used by a character in the library is added to this at request time,
# so the list grows by itself and never goes stale.
KNOWN_MODELS = [
    "zai-org/GLM-5.3",
    "Qwen/Qwen3-235B-A22B-Instruct-2507",
    "Qwen/Qwen3-8B",
    "openai/gpt-oss-120b",
    "Qwen/Qwen2.5-7B-Instruct",
]


def _model_options(*defaults):
    """Known models, plus every model seen in the library, with the defaults first."""
    seen = []
    for rec in library.list_characters(full=True):
        st = (rec.get("provenance") or {}).get("settings") or {}
        for key in ("generation_model", "name_model"):
            if st.get(key):
                seen.append(st[key])
    out = []
    for m in list(defaults) + KNOWN_MODELS + sorted(set(seen)):
        if m and m not in out:
            out.append(m)
    return out


def _live_prompts():
    """Read through assembly so prompts.py's hot reload is respected."""
    p = assembly._reload_prompts()
    return {
        "character_system": p.characterSetupSystemPrompt,
        "character_user": p.characterFullUserPrompt,
        "name_user": p.characterNamePrompt,
    }


def settings_payload():
    """
    The generation defaults, so the UI never hardcodes a model string and always shows
    what the game currently uses. Everything here is overridable per request; anything
    the client omits falls back to these.
    """
    return {
        "generation": {
            "model": config.MODEL_GENERATION,
            "temperature": config.TEMP_GENERATION,
            "reasoning_effort": config.REASONING_EFFORT_GENERATION,
            "max_tokens": config.MAX_TOKENS_GENERATION,
            "proxy_timeout": config.PROXY_TIMEOUT_GENERATION,
        },
        "name": {"model": config.MODEL_NAME, "temperature": config.TEMP_NAME},
        "dialogue": {"model": config.MODEL_DIALOGUE, "temperature": config.TEMP_DIALOGUE,
                     "max_tokens": config.MAX_TOKENS_DIALOGUE},
        "narrator": {"model": config.MODEL_NARRATOR, "temperature": config.TEMP_NARRATOR},
        "model_options": {
            "generation": _model_options(config.MODEL_GENERATION),
            "name": _model_options(config.MODEL_NAME),
            "dialogue": _model_options(config.MODEL_DIALOGUE),
        },
        # The live prompts, so the panel can show what is actually being sent and let it
        # be edited for a run without touching prompts.py -- which is game_state/, and
        # so would create drift and then block saving behind the version guard.
        "prompts": _live_prompts(),
        "genders": sorted(set(config.CHARACTER_GENDERS.values())),
        "age_range": list(config.AGE_RANGE),
        "effort_levels": ["low", "high", "max"],
        "temperature_range": [0, 2],
        # The proxy drops max_tokens (pydantic v2 discards undeclared fields), so the UI
        # should say so rather than offer a control that silently does nothing.
        "max_tokens_honoured": False,
        "game_state_version": (current_version().name if current_version() else None),
    }


def library_payload():
    """
    Every character card, plus the facet values the filter UI needs.

    The library opens at ~184 records and every experiment adds ten more, so the screen
    is unusable without filters -- and the values to filter on are already in each
    record, so they are collected here rather than hardcoded in the HTML.
    """
    chars = library.list_characters()
    facets = {k: sorted({v for v in (c.get(k) for c in chars) if v})
              for k in ("source", "game_state_version", "model", "gender")}
    facets["experiment"] = sorted({(c.get("origin") or {}).get("experiment")
                                   for c in chars
                                   if (c.get("origin") or {}).get("experiment")})
    facets["tags"] = sorted({t for c in chars for t in (c.get("tags") or [])})
    facets["verdict"] = ["good", "neutral", "bad", "unscored"]
    return {"count": len(chars), "characters": chars, "facets": facets,
            "current_version": (current_version().name if current_version() else None)}


# What the inspector columns read. The transcript carries far more per call -- every
# token count and timing field -- and shipping all of it on every turn would be most of
# a megabyte by turn ten.
CALL_FIELDS = ("timestamp", "turn_number", "call_type", "character_no", "model",
               "temperature", "system_prompt", "user_prompt", "response", "notes",
               "served_model", "total_tokens", "response_time_s")


def calls_payload():
    """Every LLM call made in the live session, oldest first."""
    if state is None:
        return {"active": False, "calls": []}
    try:
        recs = json.loads(simulator.TRANSCRIPT_JSON.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        recs = []            # the file is written on first call; before that there are none
    return {
        "active": True,
        "session_id": state.session_id,
        "calls": [{k: r.get(k) for k in CALL_FIELDS}
                  for r in recs if r.get("session_id") == state.session_id],
    }


def session_payload():
    if state is None:
        return {"active": False}
    return {
        "active": True,
        "session_id": state.session_id,
        "narrator_played": state.narrator_played,
        "source": session_source,
        "characters": {
            str(cid): char_payload(c) for cid, c in state.characters.items() if cid != 0
        },
        "dialogue": [
            {"character_id": e.character_id, "text": e.dialogue_text}
            for e in state.dialogue_entries
        ],
    }


class Handler(BaseHTTPRequestHandler):
    def _send_json(self, obj, status=200):
        body = json.dumps(obj).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _read_json(self):
        length = int(self.headers.get("Content-Length", 0))
        if not length:
            return {}
        return json.loads(self.rfile.read(length))

    def log_message(self, fmt, *args):
        pass  # quiet -- avoid noisy stdout for a local dev tool

    def do_GET(self):
        if self.path in ("/", "/index.html"):
            body = WEBAPP_HTML.read_text(encoding="utf-8").encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
        elif self.path == "/api/state":
            self._send_json(session_payload())
        elif self.path == "/api/settings":
            self._send_json(settings_payload())
        elif self.path == "/api/calls":
            self._send_json(calls_payload())
        elif self.path == "/api/runs":
            self._send_json({"runs": runstore.list_runs()})
        elif self.path.startswith("/api/runs/"):
            run_id = unquote(self.path[len("/api/runs/"):])
            try:
                self._send_json(runstore.read_run(run_id))
            except (FileNotFoundError, ValueError):
                self._send_json({"error": f"No run {run_id}."}, 404)
        elif self.path == "/api/library":
            self._send_json(library_payload())
        elif self.path.startswith("/api/library/"):
            char_id = unquote(self.path[len("/api/library/"):])
            try:
                self._send_json(library.read_character(char_id))
            except FileNotFoundError:
                self._send_json({"error": f"No character {char_id}."}, 404)
        else:
            self.send_error(404)

    def do_POST(self):
        global state
        try:
            # Once only -- rfile can be read a single time, and the active-session
            # guard needs the body before any route handler sees it.
            body = self._read_json()
            if self.path == "/api/new":
                busy = _active_session_error(body)
                if busy:
                    self._send_json({"error": busy}, status=409)
                    return
                _set_session(simulator.new_session())
                anti_dup = bool(body.get("anti_dup"))
                simulator.generate_character(state, 1)
                simulator.generate_character(state, 2, anti_dup=anti_dup)
                narrator_line = simulator.run_narrator(state)
                self._send_json({**session_payload(), "narrator_line": narrator_line})

            elif self.path == "/api/chars_only":
                busy = _active_session_error(body)
                if busy:
                    self._send_json({"error": busy}, status=409)
                    return
                _set_session(simulator.new_session())
                anti_dup = bool(body.get("anti_dup"))
                simulator.generate_character(state, 1)
                simulator.generate_character(state, 2, anti_dup=anti_dup)
                self._send_json(session_payload())

            elif self.path == "/api/library/eval":
                char_id = body.get("char_id")
                try:
                    rec = library.set_eval(
                        char_id,
                        field=body.get("field") or "eval",
                        rating=body.get("rating"),
                        notes=body.get("notes"),
                        judge_model=body.get("judge_model") or "human",
                    )
                except FileNotFoundError:
                    return self._send_json({"error": f"No character {char_id}."}, 404)
                except ValueError as e:
                    return self._send_json({"error": str(e)}, 400)
                self._send_json({"char_id": char_id,
                                 "eval": rec.get("eval"), "eval_ai": rec.get("eval_ai")})

            elif self.path == "/api/library/annotate":
                char_id = body.get("char_id")
                try:
                    rec = library.set_tags(char_id, tags=body.get("tags"),
                                           notes=body.get("notes"))
                except FileNotFoundError:
                    return self._send_json({"error": f"No character {char_id}."}, 404)
                self._send_json({"char_id": char_id, "tags": rec.get("tags"),
                                 "notes": rec.get("notes")})

            elif self.path == "/api/library/generate":
                # One character per request. The client loops and shows each as it
                # lands: a batch of ten is minutes, and a single synchronous request
                # would report nothing and lose everything to one transient 500.
                #
                # Generated against a throwaway session so a batch cannot touch the
                # snapshot a live session depends on.
                st = body.get("settings") or {}
                scratch = simulator.new_session()
                gender = st.get("gender") or random.choice(
                    sorted(set(config.CHARACTER_GENDERS.values())))
                made = simulator.generate_character_core(
                    scratch, gender=gender, settings=st, anti_dup=False)
                rec = library.new_record(
                    character={"name": made["name"], "description": made["bio"],
                               "gender": made["gender"], "age": made["age"],
                               "info_shared": []},
                    provenance={
                        "source": "generated",
                        "origin": None,
                        "game_state_version": (current_version().name
                                               if current_version() else None),
                        "drift_at_generation": drifted_files() or [],
                        "gen_session_id": scratch.session_id,
                        "settings": {
                            "generation_model": st.get("generation_model")
                                                or config.MODEL_GENERATION,
                            "generation_temperature": (st.get("generation_temperature")
                                                       if st.get("generation_temperature") is not None
                                                       else config.TEMP_GENERATION),
                            "reasoning_effort": st.get("reasoning_effort")
                                                or config.REASONING_EFFORT_GENERATION,
                            "generation_max_tokens": config.MAX_TOKENS_GENERATION,
                            "proxy_timeout": config.PROXY_TIMEOUT_GENERATION,
                            "name_model": st.get("name_model") or config.MODEL_NAME,
                            "name_temperature": (st.get("name_temperature")
                                                 if st.get("name_temperature") is not None
                                                 else config.TEMP_NAME),
                            "age_range": list(config.AGE_RANGE),
                            "provider": config.PROVIDER,
                        },
                        "prompts": {"character_system": made["system_prompt"],
                                    "character_user": made["user_prompt"],
                                    "name_user": None},
                        "prompts_source": ("custom prompts from the UI"
                                           if made.get("prompts_overridden")
                                           else "recorded at generation"),
                        "anti_duplication": {"used": made["anti_dup"],
                                             "other_char_id": None},
                        "usable": not str(made.get("sanity") or "").startswith("UNUSABLE"),
                        "sanity": made.get("sanity"),
                        "attempts": made.get("attempts"),
                        "words": made["words"], "derived_from": None, "complete": True,
                    },
                    calls=[],
                )
                library.write_character(rec)
                self._send_json({"char_id": rec["char_id"],
                                 "character": rec["character"],
                                 "words": made["words"]})

            elif self.path == "/api/session/start":
                # An empty session, so the client can drive generation one step at a
                # time and report progress between steps. /api/new still does the whole
                # thing in one call for anything that prefers that.
                busy = _active_session_error(body)
                if busy:
                    self._send_json({"error": busy}, status=409)
                    return
                _set_session(simulator.new_session())
                self._send_json(session_payload())

            elif self.path == "/api/session/character":
                if state is None:
                    return self._send_json({"error": "No active session."}, 400)
                char_no = int(body.get("char_no") or 0)
                if char_no not in (1, 2):
                    return self._send_json({"error": "char_no must be 1 or 2."}, 400)
                summary = simulator.generate_character(
                    state, char_no,
                    anti_dup=bool(body.get("anti_dup")),
                    settings=body.get("settings") or {},
                )
                self._send_json({"summary": summary, **session_payload()})

            elif self.path == "/api/runs/eval":
                try:
                    ev = runstore.set_run_eval(
                        body.get("run_id") or "",
                        field=body.get("field") or "session_eval",
                        rating=body.get("rating"), notes=body.get("notes"),
                        judge_model=body.get("judge_model") or "human")
                except (FileNotFoundError, ValueError) as exc:
                    return self._send_json({"error": str(exc)}, 400)
                self._send_json({"eval": ev})

            elif self.path == "/api/runs/call_eval":
                try:
                    ev = runstore.set_call_eval(
                        body.get("run_id") or "", int(body.get("call_index")),
                        rating=body.get("rating"), notes=body.get("notes"),
                        judge_model=body.get("judge_model") or "human")
                except (FileNotFoundError, ValueError, IndexError, TypeError) as exc:
                    return self._send_json({"error": str(exc)}, 400)
                self._send_json({"eval": ev})

            elif self.path == "/api/session/seat":
                # Two characters chosen from the library, seated in a fresh session.
                # No model is called here -- the narrator is a separate step, so the
                # client can show progress for the call that actually takes time.
                busy = _active_session_error(body)
                if busy:
                    self._send_json({"error": busy}, status=409)
                    return
                char_ids = [str(c) for c in (body.get("char_ids") or [])]
                if len(char_ids) != 2:
                    return self._send_json(
                        {"error": f"Need exactly 2 characters, got {len(char_ids)}."}, 400)
                records = []
                for cid in char_ids:
                    try:
                        records.append(library.read_character(cid))
                    except FileNotFoundError:
                        return self._send_json({"error": f"No character {cid}."}, 404)
                try:
                    seated = simulator.session_from_library(
                        records, settings=body.get("settings") or {})
                except ValueError as exc:
                    return self._send_json({"error": str(exc)}, 400)
                _set_session(seated, {"kind": "seated", "char_ids": char_ids})
                self._send_json(session_payload())

            elif self.path == "/api/run_narrator":
                if state is None:
                    return self._send_json({"error": "No active session."}, 400)
                if state.narrator_played:
                    return self._send_json({"error": "Narrator already played."}, 400)
                narrator_line = simulator.run_narrator(state)
                self._send_json({"narrator_line": narrator_line})

            elif self.path == "/api/turn":
                if state is None:
                    return self._send_json({"error": "No active session."}, 400)
                message = (body.get("message") or "").strip()
                if not message:
                    return self._send_json({"error": "Empty message."}, 400)
                result = simulator.run_player_turn(state, message)
                for r in result["replies"]:
                    char = state.characters.get(r["char_no"])
                    r["character_name"] = char.name if char else None
                self._send_json(result)

            elif self.path == "/api/save":
                if state is None:
                    return self._send_json({"error": "No active session."}, 400)
                phase = body.get("phase") or "manual"

                # Refuse to tag a run with a version that does not match the
                # prompts that produced it. The session stays in memory, so the
                # fix is: snapshot, then click Save again -- nothing is lost.
                drift = drifted_files()
                if drift and not body.get("force"):
                    current = current_version()
                    return self._send_json({"error": (
                        "game_state/ has changed since the last snapshot "
                        f"({current.name}), so this run cannot be tagged accurately.\n\n"
                        "Changed: " + ", ".join(drift) + "\n\n"
                        "Snapshot first, then click Save again:\n"
                        "  python tools/save_version.py \"slug\" \"summary\"\n\n"
                        "Your session is still open -- nothing has been lost."
                    )}, 409)

                all_records = json.load(open(simulator.TRANSCRIPT_JSON, encoding="utf-8"))
                records = [r for r in all_records if r.get("session_id") == state.session_id]
        # From memory, not from STATE_JSON: a seated session never writes that file,
        # and reading it back would save the previous session's snapshot.
                snapshot = simulator.state_snapshot_dict(state)
                current = current_version()
                game_state_version = current.name if current else None
                st = store.ExperimentStore(root=PROJECT_ROOT)
                run_id = datetime.now(timezone.utc).strftime("%Y-%m-%d_") + state.session_id
                meta = {"phase": phase, "game_state_version": game_state_version}
                if drift:
                    # Saved past the guard: the version tag is known not to match.
                    meta["drift_at_save"] = drift
                run_path = st.write_run(run_id, records, snapshot, meta=meta)
                _set_session(None)
                self._send_json({"run_id": run_id, "calls": len(records), "path": str(run_path)})

            elif self.path == "/api/abandon":
                _set_session(None)
                self._send_json({"ok": True})

            else:
                self.send_error(404)
        except Exception as e:
            self._send_json({"error": str(e)}, 500)


def main():
    server = ThreadingHTTPServer((HOST, PORT), Handler)
    url = f"http://{HOST}:{PORT}/"
    print(f"NoExit web UI running at {url}  (Ctrl+C to stop)")
    webbrowser.open(url)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
